"""Generates src/x87_tables.h: 192-bit series coefficients (needs mpmath)."""
from mpmath import mp, mpf, factorial, floor, log

mp.prec = 600

def fx(v):
    """Q2.190 fixed point, truncated."""
    m = int(floor(v * mpf(2) ** 190))
    limbs = [(m >> (64 * i)) & (2 ** 64 - 1) for i in range(3)]
    return "{ 0x%016Xull, 0x%016Xull, 0x%016Xull }" % tuple(limbs)

def table(name, comment, vals):
    n = len(vals)
    out = ["/* %s */" % comment, "static const uint64_t %s[%d][3] = {" % (name, n)]
    out += ["    %s," % fx(v) for v in vals]
    out.append("};")
    # binary exponents, for deciding how many terms are needed
    exps = [int(floor(log(v, 2) + mpf(2) ** -300)) for v in vals]
    out.append("static const int16_t %s_EXP[%d] = {" % (name, n))
    for i in range(0, n, 16):
        out.append("    " + " ".join("%d," % e for e in exps[i:i + 16]))
    out.append("};")
    return "\n".join(out)

print("/* SPDX-License-Identifier: MIT */")
print("/* Generated by tools/gen_tables.py - do not edit. */")
print("/* Series coefficients as Q2.190 fixed point: value = (m[2]:m[1]:m[0]) * 2^-190. */")
print()
print(table("TAB_INVFACT_ODD", "1 / (2k+1)!", [1 / factorial(2 * k + 1) for k in range(27)]))
print()
print(table("TAB_INVFACT_EVEN", "1 / (2k)!", [1 / factorial(2 * k) for k in range(27)]))
print()
print(table("TAB_INVFACT", "1 / (k+1)!", [1 / factorial(k + 1) for k in range(50)]))
print()
print(table("TAB_ODD_RECIP", "1 / (2k+1)", [mpf(1) / (2 * k + 1) for k in range(84)]))
